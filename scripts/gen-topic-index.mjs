// Builds src/content/topicIndex.gen.ts: the small per-topic index the startup bundle carries (titles, section
// headings, item ids and counts, Shorts). Full topic bodies load on demand (loadTopic in src/content/index.ts).
//   node scripts/gen-topic-index.mjs          write the index (run by predev / prebuild)
//   node scripts/gen-topic-index.mjs --check  exit 1 if the checked-in index is stale (run by validate and tests)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/content/topics');
const out = join(root, 'src/content/topicIndex.gen.ts');
const imp = (p) => import(pathToFileURL(join(root, p)).href);

const { PHASES } = await imp('src/content/phases.ts');
const { sectionForQuestion } = await imp('src/lib/weak.ts');
const phaseIndex = (id) => PHASES.findIndex((p) => p.id === id);

const topics = (await Promise.all(readdirSync(dir).filter((f) => f.endsWith('.ts')).map(async (f) => (await import(pathToFileURL(join(dir, f)).href)).default)))
  .filter((t) => t && typeof t === 'object' && t.id)
  .sort((a, b) => phaseIndex(a.phase) - phaseIndex(b.phase) || a.order - b.order);

// field-by-field: only what code holding a TopicMeta (src/types.ts) reads
const meta = topics.map((t) => ({
  id: t.id,
  phase: t.phase,
  order: t.order,
  title: t.title,
  subtitle: t.subtitle,
  estimatedMinutes: t.estimatedMinutes,
  tags: t.tags,
  sections: t.sections.map((s) => ({
    heading: s.heading,
    ...(s.short && { short: s.short }),
    ...(s.exercise && { exercise: true }),
    ...(s.steps && { steps: true }),
    ...(s.quickCheck && { quickCheck: { correct: s.quickCheck.correct } }),
  })),
  codeChallenges: t.codeChallenges.map((c) => ({ id: c.id, title: c.title })),
  ...(t.promptLabs && { promptLabs: t.promptLabs.map((l) => ({ id: l.id, title: l.title })) }),
  interviewQuestions: t.interviewQuestions.map((q) => ({ id: q.id, difficulty: q.difficulty, question: q.question })),
  envelopeQuestions: t.envelopeQuestions.map((q) => ({ id: q.id, question: q.question })),
  // section: the Learn section the question most likely tests (weak.ts), so Weak Areas needs no topic bodies
  test: t.test.map((q) => ({ id: q.id, difficulty: q.difficulty, correct: q.correct, ...(q.code && { code: true }), section: sectionForQuestion(t, q) })),
}));

const src = `// GENERATED by scripts/gen-topic-index.mjs from src/content/topics/*.ts. Do not edit; run: node scripts/gen-topic-index.mjs
import type { TopicMeta } from '../types';

export const TOPIC_INDEX: TopicMeta[] = ${JSON.stringify(meta, null, 1)};
`;

if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(out, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (cur !== src) {
    console.error('src/content/topicIndex.gen.ts is stale (topic content changed). Run: node scripts/gen-topic-index.mjs');
    process.exit(1);
  }
  console.log(`✓ topic index up to date (${meta.length} topics)`);
} else {
  writeFileSync(out, src);
  console.log(`Wrote src/content/topicIndex.gen.ts (${meta.length} topics)`);
}
